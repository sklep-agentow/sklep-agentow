const { chromium } = require('/usr/lib/node_modules/playwright');
const { execSync } = require('child_process');
const L=(...a)=>console.log(...a);
(async()=>{
 const b=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
 const p=await b.newPage(); let poll=0; const bledy=[];
 p.on('pageerror',e=>bledy.push(e.message));
 p.on('request',r=>{ if(r.url().includes('/wp-json/chatl/v1/rozmowa')) poll++; });
 await p.goto('http://localhost:8890/',{waitUntil:'domcontentloaded',timeout:60000});
 await p.waitForSelector('[aria-label="Otwórz czat"]',{timeout:60000});
 await p.click('[aria-label="Otwórz czat"]'); await p.waitForTimeout(2800);
 await p.fill('.chatl-pole-pytania','Pytanie pierwsze'); await p.click('[aria-label="Wyślij pytanie"]'); await p.waitForTimeout(3500);
 const s=await p.evaluate(()=>sessionStorage.getItem('chatl_sesja'));
 execSync(`docker exec strona_wp_wordpress wp --allow-root eval 'require_once WP_PLUGIN_DIR."/chatbot-live/includes/operator.php"; wp_set_current_user(1); chatl_przejmij("${s}",1);'`);
 await p.fill('.chatl-pole-pytania','Pytanie drugie — juz po przejeciu'); await p.click('[aria-label="Wyślij pytanie"]');
 await p.waitForTimeout(9000);
 const przed=poll; L('  odpytywanie CHODZI (odpytan do tej pory): '+poll);
 L('=== GOSC ZAMYKA OKNO BABELKIEM (nie klawiszem Escape) ===');
 await p.click('[aria-label="Otwórz czat"]'); await p.waitForTimeout(1200);
 L('  okno zamkniete? '+await p.evaluate(()=>!document.querySelector('.chatl-okno').classList.contains('chatl-otwarty')));
 L('  blad JS przy zamykaniu: '+JSON.stringify(bledy.filter(x=>/zatrzymaj/.test(x))));
 const przed2=poll; await p.waitForTimeout(30000);
 L('  ⛔ odpytan REST w 30 s PO ZAMKNIECIU: '+(poll-przed2)+'   (oczekiwane 0)');
 L('=== KONTROLA: to samo zamkniecie, ale klawiszem ESCAPE ===');
 await p.click('[aria-label="Otwórz czat"]'); await p.waitForTimeout(2500);
 await p.fill('.chatl-pole-pytania','Trzecie pytanie'); await p.click('[aria-label="Wyślij pytanie"]'); await p.waitForTimeout(7000);
 L('  odpytywanie znow chodzi? odpytan lacznie: '+poll);
 const przed3=poll;
 await p.keyboard.press('Escape'); await p.waitForTimeout(1200);
 L('  okno zamkniete Escape? '+await p.evaluate(()=>!document.querySelector('.chatl-okno').classList.contains('chatl-otwarty')));
 await p.waitForTimeout(30000);
 L('  odpytan REST w 30 s po ESCAPE: '+(poll-przed3)+'   <- 0 = sciezka Escape sprzata poprawnie');
 L('  wszystkie bledy JS: '+JSON.stringify([...new Set(bledy)]));
 await b.close();
})().catch(e=>{console.log('PRZYRZAD PADL: '+e.message.slice(0,250));process.exit(2)});
